package com.aresstack.serp4j.testkit.provider;

import com.aresstack.serp4j.core.model.SearchRequest;
import com.aresstack.serp4j.core.model.data.ResultType;
import com.aresstack.serp4j.core.model.data.SearchData;
import com.aresstack.serp4j.core.model.data.SearchResultItem;
import com.aresstack.serp4j.core.model.data.SerpPosition;
import com.aresstack.serp4j.core.model.id.ElementId;
import com.aresstack.serp4j.core.model.id.ProviderId;

/**
 * Deterministic, clearly synthetic search data for mocks (decision E-1: synthetic data is never presented as a real
 * provider answer). Every URL points to the reserved top-level domain {@code example.invalid}, every title starts
 * with {@code "Synthetic result"}.
 */
public final class SyntheticResults {

    /** Host of every synthetic URL; reserved by RFC 2606 and never resolvable. */
    public static final String HOST = "example.invalid";

    private SyntheticResults() {
    }

    /**
     * {@code count} organic hits for {@code request}, capped by its page limit and numbered from its offset, so
     * that pagination tests see consecutive ranks.
     */
    public static SearchData organic(ProviderId provider, SearchRequest request, int count) {
        int limit = Math.min(count, request.getPaging().getLimit());
        int offset = request.getPaging().getOffset();
        SearchData.Builder data = SearchData.builder();
        for (int i = 1; i <= limit; i++) {
            int rank = offset + i;
            data.result(SearchResultItem.builder(ElementId.of(provider.getCode() + "-" + rank), ResultType.ORGANIC,
                            url(provider, rank))
                    .title("Synthetic result " + rank + " for " + request.getQuery())
                    .snippet("Synthetic test data generated by serp4j-testkit; not a provider answer.")
                    .position(SerpPosition.ofRankInGroup(rank))
                    .build());
        }
        return data.build();
    }

    /** URL of the synthetic hit with the given rank. */
    public static String url(ProviderId provider, int rank) {
        return "https://" + HOST + "/" + provider.getCode() + "/" + rank;
    }
}
